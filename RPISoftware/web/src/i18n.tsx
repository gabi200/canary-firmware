export type Lang = "en" | "ro";
export type Vars = Record<string, string | number>;
export type TFn = (key: MsgKey, vars?: Vars) => string;

const DICTS: Record<Lang, Record<MsgKey, string>> = { en, ro };
const LOCALES: Record<Lang, string> = { en: "en-GB", ro: "ro-RO" };
const STORAGE_KEY = "canary.lang";

/** True when `key` names a dictionary entry (for keys composed from backend tokens). */
export function isMsgKey(key: string): key is MsgKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}

/** Non-hook lookup with `{name}` interpolation; unknown placeholders are left in place. */
export function translate(lang: Lang, key: MsgKey, vars?: Vars): string {
  const text = DICTS[lang][key] ?? en[key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** BCP 47 locale for Intl / toLocale*String. */
export function localeOf(lang: Lang): string {
  return LOCALES[lang];
}

/** Stored choice first, else the browser language ("ro…" -> ro), else English. */
function detectLang(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "ro") return stored;
  } catch {
    /* storage unavailable (private mode, blocked) */
  }
  try {
    if (/^ro\b/i.test(navigator.language ?? "")) return "ro";
  } catch {
    /* no navigator */
  }
  return "en";
}

let currentLang: Lang = detectLang();

/** Active language for non-React code (the API client's Accept-Language header). */
export function getLang(): Lang {
  return currentLang;
}

const pluralRules = new Map<Lang, Intl.PluralRules>();

/** CLDR plural category for `n` (RO: 1 → one, 2–19 → few, 20+ → other "de ..."; EN: one / other).
 *  Use with keys `<base>.one|few|other`. */
export function pluralCategory(lang: Lang, n: number): "one" | "few" | "other" {
  let rules = pluralRules.get(lang);
  if (!rules) {
    rules = new Intl.PluralRules(localeOf(lang));
    pluralRules.set(lang, rules);
  }
  const c = rules.select(n);
  return c === "one" || c === "few" ? c : "other";
}

/** Splits a translated string on `{name}` placeholders and drops React nodes into them. */
export function rich(text: string, nodes: Record<string, ReactNode>): ReactNode[] {
  return text.split(/(\{\w+\})/).map((part, i) => {
    const name = /^\{(\w+)\}$/.exec(part)?.[1];
    return name && name in nodes ? <Fragment key={i}>{nodes[name]}</Fragment> : part;
  });
}

interface I18nValue {
  lang: Lang;
  /** "ro-RO" / "en-GB" for Intl formatting. */
  locale: string;
  setLang: (lang: Lang) => void;
  t: TFn;
}

const I18nContext = createContext<I18nValue | null>(null);

/** Must sit inside QueryClientProvider: switching language refetches backend text. */
export function I18nProvider({ children }: { children: ReactNode }) {
  const queryClient = useQueryClient();
  const [lang, setLangState] = useState<Lang>(currentLang);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.title = translate(lang, "app.title");
  }, [lang]);

  const setLang = useCallback(
    (next: Lang) => {
      if (next === currentLang) return;
      currentLang = next; // before the refetch, so requests carry the new Accept-Language
      try {
        localStorage.setItem(STORAGE_KEY, next);
      } catch {
        /* not persisted; the choice still applies for this session */
      }
      setLangState(next);
      void queryClient.invalidateQueries();
    },
    [queryClient],
  );

  const value = useMemo<I18nValue>(
    () => ({
      lang,
      locale: localeOf(lang),
      setLang,
      t: (key, vars) => translate(lang, key, vars),
    }),
    [lang, setLang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useT(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useT must be used within I18nProvider");
  return ctx;
}
